#!/usr/bin/env bash
# Sourced by properties.sh: sets DISTRIB_FAMILY, PACKAGE_EXTENSION,
# PACKAGE_DISTRIB_NAME and PACKAGE_DISTRIB_SEPARATOR from DISTRIB.

case "$DISTRIB" in
  centos7 | el7) PACKAGE_DISTRIB_SEPARATOR="." PACKAGE_DISTRIB_NAME="el7" PACKAGE_EXTENSION="rpm" DISTRIB_FAMILY="el" ;;
  alma8 | el8) PACKAGE_DISTRIB_SEPARATOR="." PACKAGE_DISTRIB_NAME="el8" PACKAGE_EXTENSION="rpm" DISTRIB_FAMILY="el" ;;
  alma9 | el9) PACKAGE_DISTRIB_SEPARATOR="." PACKAGE_DISTRIB_NAME="el9" PACKAGE_EXTENSION="rpm" DISTRIB_FAMILY="el" ;;
  alma10 | el10) PACKAGE_DISTRIB_SEPARATOR="." PACKAGE_DISTRIB_NAME="el10" PACKAGE_EXTENSION="rpm" DISTRIB_FAMILY="el" ;;
  bullseye) PACKAGE_DISTRIB_SEPARATOR="+" PACKAGE_DISTRIB_NAME="deb11u1" PACKAGE_EXTENSION="deb" DISTRIB_FAMILY="debian" ;;
  bookworm) PACKAGE_DISTRIB_SEPARATOR="+" PACKAGE_DISTRIB_NAME="deb12u1" PACKAGE_EXTENSION="deb" DISTRIB_FAMILY="debian" ;;
  trixie) PACKAGE_DISTRIB_SEPARATOR="+" PACKAGE_DISTRIB_NAME="deb13u1" PACKAGE_EXTENSION="deb" DISTRIB_FAMILY="debian" ;;
  jammy) PACKAGE_DISTRIB_SEPARATOR="-" PACKAGE_DISTRIB_NAME="0ubuntu.22.04" PACKAGE_EXTENSION="deb" DISTRIB_FAMILY="ubuntu" ;;
  noble) PACKAGE_DISTRIB_SEPARATOR="-" PACKAGE_DISTRIB_NAME="0ubuntu.24.04" PACKAGE_EXTENSION="deb" DISTRIB_FAMILY="ubuntu" ;;
  *)
    echo "::error::Distrib $DISTRIB cannot be parsed"
    exit 1
    ;;
esac

{
  echo "package_distrib_separator=$PACKAGE_DISTRIB_SEPARATOR"
  echo "package_distrib_name=$PACKAGE_DISTRIB_NAME"
  echo "package_extension=$PACKAGE_EXTENSION"
  echo "distrib_family=$DISTRIB_FAMILY"
} >> "$GITHUB_OUTPUT"
